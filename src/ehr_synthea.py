def _read(name):
    df = pd.read_csv(SYNTHEA_DIR / f"{name}.csv", low_memory=False)
    df.columns = [c.upper() for c in df.columns]
    return df


def _shift_dates(frames, date_cols, snapshot):
    """Synthea simulates up to the day it is run. Shift every date so the end of the
    simulation lines up with the start of our monitoring year. Ages stay consistent."""
    latest = max(pd.to_datetime(f[c], errors="coerce", utc=True).max()
                 for f, cols in zip(frames, date_cols) for c in cols)
    offset = latest.tz_localize(None).normalize() - pd.Timestamp(snapshot)
    for f, cols in zip(frames, date_cols):
        for c in cols:
            f[c] = pd.to_datetime(f[c], errors="coerce", utc=True).dt.tz_localize(None) - offset
    return offset


def load_synthea(snapshot=START_DATE):
    pats, cond, obs, meds = _read("patients"), _read("conditions"), _read("observations"), _read("medications")
    imm = _read("immunizations") if (SYNTHEA_DIR / "immunizations.csv").exists() else pd.DataFrame(columns=["DATE", "PATIENT", "DESCRIPTION"])
    _shift_dates([pats, cond, obs, meds, imm],
                 [["BIRTHDATE", "DEATHDATE"], ["START", "STOP"], ["DATE"], ["START", "STOP"], ["DATE"]], snapshot)
    snap = pd.Timestamp(snapshot)

    cond["CODE"] = cond.CODE.astype(str)
    copd = cond[cond.CODE.isin(COPD_SNOMED) & (cond.START <= snap)].sort_values("START").groupby("PATIENT").first()
    alive = pats[(pats.DEATHDATE.isna()) | (pats.DEATHDATE > snap)].set_index("ID")
    ids = copd.index.intersection(alive.index)

    p = pd.DataFrame(index=ids)
    p["synthea_id"] = ids
    p["age"] = ((snap - alive.loc[ids, "BIRTHDATE"]).dt.days / 365.25).astype(int)
    p["sex"] = alive.loc[ids, "GENDER"].values
    p["copd_type"] = copd.loc[ids, "CODE"].map(COPD_SNOMED)
    p["years_since_copd_diagnosis"] = ((snap - copd.loc[ids, "START"]).dt.days / 365.25).round(1)

    o = obs[obs.PATIENT.isin(ids) & (obs.DATE <= snap)].sort_values("DATE")
    for name, code in LOINC.items():
        last = o[o.CODE.astype(str) == code].groupby("PATIENT").VALUE.last()
        p[name] = last.reindex(ids).values
    for c in ["fev1_fvc", "bmi", "systolic_bp", "diastolic_bp", "heart_rate", "resp_rate", "hemoglobin"]:
        p[c] = pd.to_numeric(p[c], errors="coerce")
    p["fev1_fvc_readings"] = o[o.CODE.astype(str) == LOINC["fev1_fvc"]].groupby("PATIENT").size().reindex(ids).fillna(0).astype(int).values
    sm = p.smoking.fillna("").str.lower()
    p["smoking_status"] = np.select([sm.str.contains("never"), sm.str.contains("ex-smoker|former")],
                                    ["never", "former"], default=np.where(sm == "", "unknown", "current"))
    p = p.drop(columns="smoking")

    active = cond[cond.PATIENT.isin(ids) & (cond.START <= snap) & (cond.STOP.isna() | (cond.STOP > snap))]
    desc = active.DESCRIPTION.str.lower()
    for flag, words in COMORBIDITY_KEYWORDS.items():
        match = desc.str.contains("|".join(words)) & ~desc.str.contains("prediabetes")
        hit = active[match].PATIENT.unique()
        p[flag] = p.index.isin(hit).astype(int)

    p["obesity"] = (p.bmi >= 30).astype(int)

    m = meds[meds.PATIENT.isin(ids) & (meds.START <= snap) & (meds.STOP.isna() | (meds.STOP > snap))]
    md = m.DESCRIPTION.str.lower()
    p["on_maintenance_inhaler"] = p.index.isin(m[md.str.contains("fluticasone|salmeterol|tiotropium|budesonide|formoterol")].PATIENT).astype(int)
    p["on_rescue_inhaler"] = p.index.isin(m[md.str.contains("albuterol|salbutamol")].PATIENT).astype(int)
    dev = _read("devices") if (SYNTHEA_DIR / "devices.csv").exists() else pd.DataFrame(columns=["START", "STOP", "PATIENT", "DESCRIPTION"])
    if len(dev):
        dev["START"] = pd.to_datetime(dev.START, errors="coerce", utc=True).dt.tz_localize(None)
        dev["STOP"] = pd.to_datetime(dev.STOP, errors="coerce", utc=True).dt.tz_localize(None)
    oxy = dev[dev.DESCRIPTION.str.lower().str.contains("oxygen", na=False) & (dev.START <= snap) & (dev.STOP.isna() | (dev.STOP > snap))]
    p["home_oxygen"] = p.index.isin(oxy.PATIENT).astype(int)
    flu = imm[(imm.DATE <= snap) & (imm.DATE > snap - pd.Timedelta(days=365)) & imm.DESCRIPTION.str.lower().str.contains("influenza", na=False)]
    p["influenza_vaccinated"] = p.index.isin(flu.PATIENT).astype(int)
    return p.reset_index(drop=True)


def young_cohort(seed=SEED + 1):
    """Synthea's COPD module never produces patients under ~50, but in India COPD often starts earlier
    (cooking smoke, bidi smoking, past tuberculosis). These younger patients are drawn by us (India overlay,
    synthetic) with the same fields as the Synthea records. Shares below are ASSUMPTIONS."""
    rng = np.random.default_rng(seed)
    ages = np.concatenate([rng.integers(lo, hi + 1, n) for (lo, hi), n in YOUNG_COHORT["age_bands"].items()])
    n = len(ages)
    sex = np.where(rng.random(n) < 0.55, "F", "M")          # biomass smoke makes early COPD common in women
    smoke = np.where(sex == "M", rng.choice(["current", "former", "never"], n, p=[.45, .25, .30]),
                     rng.choice(["current", "former", "never"], n, p=[.10, .10, .80]))
    bmi = np.clip(rng.normal(21.5, 3.5, n), 15, 38).round(1)
    y = pd.DataFrame({
        "synthea_id": "", "age": ages, "sex": sex,
        "copd_type": rng.choice(list(COPD_SNOMED.values()), n),
        "years_since_copd_diagnosis": np.clip(rng.exponential(3, n), 0.3, ages - 25).round(1),
        "fev1_fvc": np.nan, "bmi": bmi,
        "systolic_bp": rng.normal(122, 12, n).round(0), "diastolic_bp": rng.normal(78, 8, n).round(0),
        "heart_rate": np.nan, "resp_rate": np.nan, "hemoglobin": np.nan, "fev1_fvc_readings": 0,
        "smoking_status": smoke,
        "hypertension": (rng.random(n) < 0.12).astype(int), "diabetes": (rng.random(n) < 0.08).astype(int),
        "ischemic_heart_disease": (rng.random(n) < 0.03).astype(int), "heart_failure": (rng.random(n) < 0.01).astype(int),
        "anemia": (rng.random(n) < np.where(sex == "F", 0.20, 0.05)).astype(int),
        "obesity": (bmi >= 30).astype(int), "on_maintenance_inhaler": 0, "on_rescue_inhaler": 1,
        "home_oxygen": (rng.random(n) < 0.02).astype(int), "influenza_vaccinated": 0,
        "gold_stage": rng.choice([1, 2, 3, 4], n, p=[.25, .45, .22, .08]),      # milder on average when younger
        "record_source": "India overlay (synthetic, ours)",
    })
    return y


def stage_by_rank(values, rng):
    """Synthea's lung-function value runs very low (median ~25), which would make two thirds of patients GOLD 4.
    Keep Synthea's ordering of who is sicker, but assign stages in typical clinic shares (config.GOLD_SHARES)."""
    v = values.copy()
    v[v.isna()] = rng.uniform(v.min(), v.max(), v.isna().sum())
    pct = v.rank(pct=True, method="first")                      # low lung function -> low percentile -> severe
    cut = np.cumsum([GOLD_SHARES[k] for k in (4, 3, 2)])
    return pd.Series(np.select([pct <= cut[0], pct <= cut[1], pct <= cut[2]], [4, 3, 2], 1), index=values.index)


def gold_stage_from_value(v):
    """Synthea's COPD module stages its lung-function value with FEV1 %-predicted style bands."""
    if pd.isna(v):
        return np.nan
    v = v * 100 if v <= 1.5 else v
    return 1 if v >= 80 else 2 if v >= 50 else 3 if v >= 30 else 4


def india_overlay(p, seed=SEED):
    """Fields Synthea cannot produce. All drawn by us and labelled as synthetic overlay."""
    rng = np.random.default_rng(seed)
    n = len(p)
    p = p.copy()
    syn = p.record_source.eq("Synthea")
    p.loc[syn, "gold_stage"] = stage_by_rank(p.loc[syn, "fev1_fvc"], rng)
    p["gold_stage"] = p.gold_stage.astype(int)
    # Synthea records nearly everyone with COPD as a former smoker; in India many keep smoking (ASSUMPTION: a quarter)
    p.loc[syn & p.smoking_status.eq("former") & (rng.random(n) < 0.25), "smoking_status"] = "current"
    p["lung_function_pct"] = np.where(p.fev1_fvc.isna(), np.nan, np.where(p.fev1_fvc <= 1.5, p.fev1_fvc * 100, p.fev1_fvc)).round(0)

    names = list(CITIES)
    p["city"] = rng.choice(names, n, p=[CITIES[c]["share"] for c in names])
    p["region"] = p.city.map(lambda c: CITIES[c]["region"])
    female = p.sex.eq("F")
    p["display_name"] = [f"{rng.choice(FIRST_F if f else FIRST_M)} {rng.choice(LAST)}" for f in female]
    p["patient_id"] = [f"MOM-{i:04d}" for i in range(1, n + 1)]

    p["biomass_fuel_exposure"] = (rng.random(n) < np.where(female, 0.45, 0.15)).astype(int)
    p["tobacco_type"] = np.where(p.smoking_status.isin(["current", "former"]),
                                 rng.choice(["bidi", "cigarette", "both"], n, p=[.45, .40, .15]), "none")
    freq = cal("frequent_exacerbator_share_by_stage")
    rate = cal("exac_rate_per_year_by_stage")
    p["frequent_exacerbator"] = (rng.random(n) < p.gold_stage.map(freq)).astype(int)
    lam = p.gold_stage.map(rate) * np.where(p.frequent_exacerbator == 1, cal("frequent_exacerbator_rate_multiplier"), 0.7)
    p["exacerbations_prior_year"] = np.minimum(rng.poisson(lam), 6)
    p["blood_eosinophils_per_ul"] = np.clip(rng.lognormal(5.2, 0.6, n), 40, 900).round(0).astype(int)
    p["serpina1_variant"] = (rng.random(n) < 0.02).astype(int)      # alpha-1 antitrypsin deficiency marker
    # Synthea vaccinates on the US schedule; replace with a low India-like coverage (ASSUMPTION)
    p["influenza_vaccinated"] = (rng.random(n) < 0.15).astype(int)
    p["adherence_habit"] = np.clip(rng.beta(5, 2, n), 0.15, 0.99).round(2)
    p["pollution_sensitivity"] = np.clip(rng.normal(1.0, 0.35, n), 0.2, 2.2).round(2)
    # Synthea gives few inhaler types; ensure everyone has a rescue inhaler and stage-appropriate maintenance
    p["on_rescue_inhaler"] = 1
    p["on_maintenance_inhaler"] = np.where(p.gold_stage >= 2, 1, p.on_maintenance_inhaler)
    first = ["patient_id", "display_name", "age", "sex", "city", "region"]
    return p[first + [c for c in p.columns if c not in first]]


